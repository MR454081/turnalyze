from datasets import load_dataset
import re

ds = load_dataset('knarasi1/student_and_llm_essays', split='train', streaming=True, trust_remote_code=False)

for i, row in enumerate(ds):
    if i >= 3:
        break
    essay = row.get('essay', '')
    print(f"=== ROW {i} ===")
    
    # Find "Essay: " marker
    essay_match = re.search(r'\bEssay:\s*(.*?)\n', essay, re.DOTALL)
    if essay_match:
        # The essay starts after "Essay: "
        start_pos = essay_match.start(1)
        # Find the end - it's before "Determine if..."
        end_match = re.search(r'Determine if the essay if student-written or generated by a Large Language Model\. \[/INST\]', essay)
        if end_match:
            essay_text = essay[start_pos:end_match.start()]
            print(f"Extracted essay length: {len(essay_text)}")
            print(f"First 200 chars: {repr(essay_text[:200])}")
            print(f"Last 200 chars: {repr(essay_text[-200:])}")
    print()
